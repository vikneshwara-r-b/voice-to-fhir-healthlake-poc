"""AWS HealthScribe: start jobs and turn its output into turns, insights and a clinical note.

HealthScribe adds what the Transcribe Medical path lacks: speaker roles (CLINICIAN_n /
PATIENT_n), a section label per dialogue segment, its own clinical entities, and an
AI-generated clinical note whose sentences carry EvidenceLinks to transcript segments.
"""

import re

# Template -> (display name, LOINC code, LOINC display) for the DocumentReference written on approval.
TEMPLATES = {
    "HISTORY_AND_PHYSICAL": ("History and physical", "34117-2", "History and physical note"),
    "PHYSICAL_SOAP": ("SOAP (physical health)", "11506-3", "Progress note"),
    "DAP": ("DAP", "11506-3", "Progress note"),
    "GIRPP": ("GIRPP", "11506-3", "Progress note"),
    "BIRP": ("BIRP", "11506-3", "Progress note"),
    "SIRP": ("SIRP", "11506-3", "Progress note"),
    "BEHAVIORAL_SOAP": ("SOAP (behavioral health)", "11506-3", "Progress note"),
}
PRONOUNS = ("HE_HIM", "SHE_HER", "THEY_THEM")
ENGINE_LABELS = {
    "transcribe": "Amazon Transcribe Medical + Amazon Comprehend Medical",
    "healthscribe": "AWS HealthScribe + Amazon Comprehend Medical",
}
_ROLE = re.compile(r"^(CLINICIAN|PATIENT)_(\d+)$")


def job_name(prefix: str, draft_id: str, template: str, run: int) -> str:
    """Also the S3 key prefix of the job's output (see the data access role in the CDK)."""
    return f"{prefix}-scribe-{draft_id}-{template.lower().replace('_', '')}-{run}"


def section_title(name: str) -> str:
    return name.replace("_", " ").capitalize() if name else "Other"


def _role(participant: str) -> tuple[str, str]:
    m = _ROLE.match(participant or "")
    if not m:
        return participant or "UNKNOWN", "Speaker"
    kind = "Clinician" if m[1] == "CLINICIAN" else "Patient"
    return participant, kind if m[2] == "0" else f"{kind} {int(m[2]) + 1}"


def parse_transcript(doc: dict) -> tuple[list[dict], dict, list[dict]]:
    """Return (turns, segments by id, insights). Consecutive segments of one speaker form a turn."""
    conversation = doc.get("Conversation", {})
    turns, segments = [], {}
    for seg in conversation.get("TranscriptSegments", []):
        speaker, role = _role(seg.get("ParticipantDetails", {}).get("ParticipantRole"))
        section = seg.get("SectionDetails", {}).get("SectionName")
        entry = {"id": seg.get("SegmentId"), "text": seg.get("Content", "").strip(), "section": section, "role": role}
        if not entry["text"]:
            continue
        segments[entry["id"]] = entry
        if turns and turns[-1]["speaker"] == speaker:
            turn = turns[-1]
            turn["text"] += " " + entry["text"]
            turn["endTime"] = seg.get("EndAudioTime", turn["endTime"])
            turn["segments"].append({"id": entry["id"], "text": entry["text"], "section": section})
        else:
            turns.append({"index": len(turns), "speaker": speaker, "role": role, "text": entry["text"],
                          "startTime": seg.get("BeginAudioTime"), "endTime": seg.get("EndAudioTime"),
                          "confidence": None,
                          "segments": [{"id": entry["id"], "text": entry["text"], "section": section}]})
    insights = [
        {"category": i.get("Category"), "type": i.get("Type"),
         "text": " ".join(s.get("Content", "") for s in i.get("Spans", [])).strip()}
        for i in conversation.get("ClinicalInsights", []) if i.get("InsightType") == "ClinicalEntity"
    ]
    return turns, segments, insights


def parse_note(doc: dict, template: str, segments: dict) -> dict:
    sections = []
    for section in doc.get("ClinicalDocumentation", {}).get("Sections", []):
        items = []
        for summary in section.get("Summary", []):
            text = (summary.get("SummarizedSegment") or "").strip()
            if not text:
                continue
            evidence = [segments[e["SegmentId"]] for e in summary.get("EvidenceLinks", [])
                        if e.get("SegmentId") in segments]
            items.append({"text": text, "evidence": [{"role": e["role"], "text": e["text"]} for e in evidence]})
        if items:
            sections.append({"name": section.get("SectionName"), "title": section_title(section.get("SectionName")),
                             "items": items})
    title, _, _ = TEMPLATES.get(template, (template, None, None))
    return {"template": template, "templateTitle": title, "sections": sections}


def note_text(note: dict) -> str:
    """Plain-text rendering of the note for the DocumentReference attachment."""
    lines = [f"{note['templateTitle']} (AI-generated by AWS HealthScribe; reviewed by clinician)", ""]
    for section in note["sections"]:
        lines.append(section["title"].upper())
        lines.extend(f"- {item['text']}" for item in section["items"])
        lines.append("")
    return "\n".join(lines).strip()


def start_job(client, *, name: str, bucket: str, media_uri: str, role_arn: str, template: str,
              channels: int, pronouns: str | None) -> None:
    if channels == 2:  # clinician on the left channel, patient on the right (sample convention)
        settings = {"ChannelIdentification": True}
        extra = {"ChannelDefinitions": [{"ChannelId": 0, "ParticipantRole": "CLINICIAN"},
                                        {"ChannelId": 1, "ParticipantRole": "PATIENT"}]}
    else:
        settings = {"ShowSpeakerLabels": True, "MaxSpeakerLabels": 2}
        extra = {}
    settings["ClinicalNoteGenerationSettings"] = {"NoteTemplate": template}
    if pronouns in PRONOUNS:
        extra["MedicalScribeContext"] = {"PatientContext": {"Pronouns": pronouns}}
    client.start_medical_scribe_job(
        MedicalScribeJobName=name,
        Media={"MediaFileUri": media_uri},
        OutputBucketName=bucket,
        DataAccessRoleArn=role_arn,
        Settings=settings,
        **extra,
    )
